   private void loadUtangRecords() {
    StoreData.utang.setRowCount(0); //moves all rows
    String sql = "SELECT u.utang_id, c.customer_lastname, "
            + "c.customer_firstname, c.contact_number, "
            + "p.product_name, u.amount, u.amount_paid, "
            + "u.due_date, u.status "
            + "FROM utang_record u "
            + "JOIN customer c ON u.customer_id = c.customer_id "
            + "JOIN product p ON u.product_id = p.product_id "
            + "ORDER BY u.utang_id DESC";
//so ang JOIN kay para ma connnect/ma mattch and id sa cosutomer row table

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {   //preparethe SQL query before executing it
        try (ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                StoreData.utang.addRow(new Object[]{
                    rs.getInt("utang_id"),
                    rs.getString("customer_lastname"),
                    rs.getString("customer_firstname"),
                    rs.getString("contact_number"),
                    rs.getString("product_name"),
                    rs.getDouble("amount"),
                    rs.getDouble("amount_paid"),
                    rs.getDate("due_date"),
                    rs.getString("status")
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading utang records: " + e.getMessage());
    }
}
