    private void REMOVEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_REMOVEActionPerformed
    int row = TABLE.getSelectedRow();   //mag sellek og row
    if (row == -1) {    //f wlay gi selek
        JOptionPane.showMessageDialog(this,
                "Please select an utang record.");  //kni mu pop up
        return; //balik gng
    }

    int modelRow = TABLE.convertRowIndexToModel(row);
    int utangId = Integer.parseInt(
            TABLE.getModel().getValueAt(modelRow, 0).toString()
    );

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Move this record to Archive?",
            "Confirm Void",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String insertSQL =
            "INSERT INTO utang_report "
            + "(utang_id, customer_lastname, customer_firstname, "
            + "contact_number, item, amount, amount_paid, due_date, status) "
            + "SELECT u.utang_id, c.customer_lastname, "
            + "c.customer_firstname, c.contact_number, "
            + "p.product_name, u.amount, u.amount_paid, "
            + "u.due_date, u.status "
            + "FROM utang_record u "
            + "JOIN customer c ON u.customer_id = c.customer_id "
            + "JOIN product p ON u.product_id = p.product_id "
            + "WHERE u.utang_id = ?";

    String deleteSQL =
            "DELETE FROM utang_record "
            + "WHERE utang_id = ?";

    try (Connection con = DBConnection.getConnection()) {
        if (con == null) {
            JOptionPane.showMessageDialog(this,
                    "Database connection failed.");
            return;
        }

        con.setAutoCommit(false);

        try {
            // sve the selectd record to the archive databas
            try (PreparedStatement pst = con.prepareStatement(insertSQL)) {
                pst.setInt(1, utangId);
                int inserted = pst.executeUpdate();
                if (inserted != 1) {
                    throw new SQLException(
                            "The utang record was not found or could not be archived."
                    );
                }
            }

            // mama delt  the original record only after archivng it
            try (PreparedStatement pst = con.prepareStatement(deleteSQL)) {
                pst.setInt(1, utangId);
                int deleted = pst.executeUpdate();
                if (deleted != 1) {
                    throw new SQLException(
                            "The original utang record could not be removed."
                    );
                }
            }

            // sve both database ma chnge sha t2gethe
            con.commit();
        } catch (SQLException e) {
            con.rollback(); //mabalik sa database ang mga changes if wallaa a na commit, incase ni sha if naay erreer
            throw e;
        }
        // updat the GUI after the database transaction succeeds   
        loadUtangRecords();
        JOptionPane.showMessageDialog(this,
                "Utang record successfully moved to Archive!");
    } catch (SQLException e) {  //naay eror, wlaa na update
        JOptionPane.showMessageDialog(this,
                "Unable to void utang: " + e.getMessage());
    }
    }//GEN-LAST:event_REMOVEActionPerformed

    private void updaterecordsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updaterecordsActionPerformed
        int row = TABLE.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a record first.");
        return;
    }

    String[] choices = {
        "Contact No.", "Items", "Amount Paid", "Due Date", "Cancel"
    };
    String choice = (String) JOptionPane.showInputDialog(   //pop up
        this,
        "Which information do you want to update?",
        "Update Utang Record",
        JOptionPane.QUESTION_MESSAGE,
        null,
        choices,
        choices[0]
    );

    if (choice == null || choice.equals("Cancel")) {    //f cancel dipili kay muballik
        return;
    }

    String input = JOptionPane.showInputDialog(
        this, "Enter new " + choice + ":"
    );

    if (input == null || input.trim().isEmpty()) {  //f empty or gii exx llang
        return;
    }

    int utangId = Integer.parseInt(TABLE.getValueAt(row, 0).toString());
    String value = input.trim();

    try (Connection con = DBConnection.getConnection()) {
        if (con == null) {
            JOptionPane.showMessageDialog(this, "Database connection failed.");
            return;
        }

        if (choice.equals("Contact No.")) {
            String sql = "UPDATE customer SET contact_number = ? "
                       + "WHERE customer_id = "
                       + "(SELECT customer_id FROM utang_record WHERE utang_id = ?)";

            try (PreparedStatement pst = con.prepareStatement(sql)) {
                pst.setString(1, value);
                pst.setInt(2, utangId);
                pst.executeUpdate();
            }

        } else if (choice.equals("Items")) {
            int productId;
            String findProduct = "SELECT product_id FROM product WHERE product_name = ?";
            try (PreparedStatement pst = con.prepareStatement(findProduct)) {
                pst.setString(1, value);
                try (ResultSet rs = pst.executeQuery()) {
                    if (!rs.next()) {
                        JOptionPane.showMessageDialog(this, "Product not found.");
                        return;
                    }
                    productId = rs.getInt("product_id");
                }
            }

            String sql = "UPDATE utang_record SET product_id = ? WHERE utang_id = ?";
            try (PreparedStatement pst = con.prepareStatement(sql)) {
                pst.setInt(1, productId);
                pst.setInt(2, utangId);
                pst.executeUpdate();
            }

        } else if (choice.equals("Due Date")) {
            String sql = "UPDATE utang_record SET due_date = ? WHERE utang_id = ?";
            try (PreparedStatement pst = con.prepareStatement(sql)) {
                pst.setDate(1, java.sql.Date.valueOf(value));
                pst.setInt(2, utangId);
                pst.executeUpdate();
            }

        } else if (choice.equals("Amount Paid")) {
            double paid = Double.parseDouble(value);
            double amount = numberAt(row, 5);
            if (paid < 0 || paid > amount) {
                JOptionPane.showMessageDialog(this,
                    "Amount paid must be between zero and the total amount.");
                return;
            }

            String status;
            if (paid == amount) {
                status = "paid";    //f equall giibayad
            } else if (paid > 0) {  //f nag data2 lng sha
                status = "partially paid";
            } else {
                status = "unpaid";
            }

            String sql = "UPDATE utang_record "
                       + "SET amount_paid = ?, status = ? WHERE utang_id = ?";
            try (PreparedStatement pst = con.prepareStatement(sql)) {
                pst.setDouble(1, paid);
                pst.setString(2, status);
                pst.setInt(3, utangId);
                pst.executeUpdate();
            }
        }

        loadUtangRecords();
        JOptionPane.showMessageDialog(this, "Record updated successfully!");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Enter a valid number or date in YYYY-MM-DD format.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Database update failed: " + e.getMessage());
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this,
            "Enter the due date in YYYY-MM-DD format.");
    }
    }//GEN-LAST:event_updaterecordsActionPerformed
        private double numberAt(int row, int column) {  
        Object value = TABLE.getValueAt(row, column);   //ikuha ang value sa cell sa table base sa row ug column, unya gibutang sa value
        if (value == null || value.toString().trim().isEmpty()) return 0;
        return Double.parseDouble(value.toString().trim());
    }

    private void addToUtangReports(int row) {
        Object[] record = new Object[TABLE.getColumnCount()];   //aaray pra sa table
        for (int i = 0; i < record.length; i++) {
            record[i] = TABLE.getValueAt(row, i);   //kopya ang value sa  cell sa gipili na row sa sa record array
        }

        // Keep only one report entry for each ID.
        for (int i = 0; i < StoreData.utangReports.getRowCount(); i++) {    //chik etch row
            Object id = StoreData.utangReports.getValueAt(i, 0);
            if (id != null && record[0] != null && id.toString().equals(record[0].toString())) {    //f nay ngka double
                StoreData.utangReports.removeRow(i);
                break;
            }
        }
        StoreData.utangReports.addRow(record);
    }
    private void searchtxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchtxtActionPerformed
    String search = SEARCHFIELD.getText().trim();
        if (search.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please type a customer name to search.");
            return;
        }

        for (int i = 0; i < TABLE.getRowCount(); i++) {
            Object lastName = TABLE.getValueAt(i, 1);
            Object firstName = TABLE.getValueAt(i, 2);
            String fullName = (lastName == null ? "" : lastName.toString()) + " "
                + (firstName == null ? "" : firstName.toString());
            if (fullName.toLowerCase().contains(search.toLowerCase())) {
                TABLE.setRowSelectionInterval(i, i);
                TABLE.scrollRectToVisible(TABLE.getCellRect(i, 0, true));
                return;
            }
        }
        JOptionPane.showMessageDialog(this, "Utang record not found.");
    }//GEN-LAST:event_searchtxtActionPerformed

