    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
    String enteredUsername = username.getText().trim();     //kwaon ang data sa textfield
    String enteredPassword = new String(pass.getPassword());

    if (enteredUsername.isEmpty() || enteredPassword.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter username and password.");
        return;
    }

    String sql = "SELECT owner_id, username "       //para match ang naassa databse
               + "FROM login_page "
               + "WHERE username = ? AND password = ?";

    try (Connection con = DBConnection.getConnection()) {   //e try na connect sa daatabase

        if (con == null) { //e chik f wala nay eferense sa databe ten e stop
            JOptionPane.showMessageDialog(this,
                    "Cannot connect to the database.");
            return;
        }

        try (PreparedStatement pst = con.prepareStatement(sql)) {   //pra mapulihan angg mga ?

            pst.setString(1, enteredUsername);  //ang usrname e butang sa ?
            pst.setString(2, enteredPassword);

            try (ResultSet rs = pst.executeQuery()) {   //g run n compare if same ba sa databs
                if (rs.next()) {

                    loggedInOwnerId = rs.getInt("owner_id");

                    JOptionPane.showMessageDialog(this,
                            "Login successful! Welcome, "
                            + rs.getString("username") + "!");

                    Dashbard main = new Dashbard();
                    main.setVisible(true);
                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(this,
                            "Invalid username or password.");
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Login error: " + e.getMessage());
    }
    }//GEN-LAST:event_loginActionPerformed

